import { mkdir, writeFile } from "node:fs/promises";
import { generateTokenCss } from "../src/design-system/generateCss.js";

const outputDir = new URL("../dist/", import.meta.url);
const runtimeManifestPath = new URL("../src/design-system/generatedManifest.js", import.meta.url);
const { css, manifest } = generateTokenCss();

await mkdir(outputDir, { recursive: true });
await writeFile(new URL("trama-ui-tokens.css", outputDir), css);
await writeFile(new URL("trama-ui-tokens.manifest.json", outputDir), `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(runtimeManifestPath, [
  "// Generated by scripts/build-design-tokens.mjs. Do not edit by hand.",
  `export const DESIGN_SYSTEM_MANIFEST = Object.freeze(${JSON.stringify({
    schemaVersion: manifest.schemaVersion,
    theme: manifest.theme,
    hash: manifest.hash,
    tokenCount: manifest.tokenCount
  }, null, 2)});`,
  ""
].join("\n"));
console.log(`Generated ${manifest.tokenCount} design tokens (${manifest.hash.slice(0, 12)}).`);
